// Coach roles in preview: members get no coach switch and pick from PX coaches;
// the owner sees the team and can add/remove coaches.
import { chromium, devices } from 'playwright';
import { createServer } from 'node:http';
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const html = readFileSync('dist/index.html');
const server = createServer((_, res) => { res.writeHead(200, { 'content-type': 'text/html' }); res.end(html); }).listen(0);
const url = `http://127.0.0.1:${server.address().port}/`;
const browser = await chromium.launch();
const ctx = await browser.newContext({ ...devices['iPhone 13'] });
await ctx.route(/fonts\./, (r) => r.abort());
const page = await ctx.newPage(); page.setDefaultTimeout(8000);
const errors = []; page.on('pageerror', (e) => errors.push(e.message));
const results = [];
const step = async (n, fn) => { try { await fn(); results.push(['PASS', n]); } catch (e) { results.push(['FAIL', n, e.message.split('\n')[0]]); await page.screenshot({ path: `e2e/shots/rfail-${results.length}.png` }).catch(() => {}); } };

await step('member preview: no coach switch, coach desk hidden, PX coach in the list', async () => {
  await page.goto(url + '#welcome');
  await page.getByTestId('cta-start').click();
  await page.getByTestId('goal-strength').click();
  for (let i = 0; i < 6; i++) await page.getByTestId('onb-next').click();
  await page.getByTestId('onb-finish').click();
  await page.getByTestId('open-chat').waitFor();
  await page.goto(url + '#you');
  await page.getByTestId('demo-on').click();
  await page.getByTestId('demo-banner').waitFor();
  await page.getByTestId('ftab-coach').click();
  assert.equal(await page.getByRole('switch', { name: 'Coach mode' }).count(), 0);
  assert.equal(await page.getByTestId('staff-badge').count(), 0);
  await page.goto(url + '#you');
  assert.equal(await page.getByTestId('enter-coach').count(), 0);
  await page.getByTestId('demo-exit').click();
});
await step('coach preview: owner badge, team list, add and remove a coach', async () => {
  await page.getByTestId('demo-coach').click();
  await page.getByTestId('demo-banner').waitFor();
  await page.getByTestId('ftab-coach').click();
  await page.getByTestId('staff-badge').getByText('You run PX coaching').waitFor();
  await page.getByTestId('team').getByText('PX Coach').waitFor();
  await page.getByTestId('client-request').getByText('Taylor').waitFor();
  await page.getByTestId('team-code').fill('ZZZZ9999');
  await page.getByTestId('team-add').click();
  await page.getByText('No one has that code').first().waitFor();
  await page.getByTestId('team-code').fill('JRDN2222');
  await page.getByTestId('team-add').click();
  await page.getByText('Jordan is now a PX coach').first().waitFor();
  assert.equal(await page.getByTestId('team-member').count(), 3);
  await page.screenshot({ path: 'e2e/shots/roles-owner.png', fullPage: true });
  await page.getByTestId('team-remove').last().click();
  await page.getByRole('alertdialog').getByRole('button', { name: 'Remove', exact: true }).click();
  await page.getByText('Coach removed').first().waitFor();
  assert.equal(await page.getByTestId('team-member').count(), 2);
  await page.goto(url + '#you');
  await page.getByTestId('enter-coach').waitFor();
});
await step('no page errors', async () => assert.deepEqual(errors, []));
for (const r of results) console.log(r.join('  '));
console.log(`${results.filter((r) => r[0] === 'PASS').length}/${results.length} passed`);
await browser.close(); server.close();
process.exit(results.every((r) => r[0] === 'PASS') ? 0 : 1);
